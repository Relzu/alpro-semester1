# Operator Aritmatika (+ - * / % ** //)

a = 15
b = 4
print("Operasi Aritmatika:")
print(a + b)  # Penjumlahan
print(a - b)  # Pengurangan
print(a * b)  # Perkalian
print(a / b)  # Pembagian
print(a % b)  # Modulus (sisa bagi)
print(a ** b) # Pangkat
print(a // b) # Pembagian Bulat

#Operator Penugasan (=, +=, -=, *=, /=, %=, **=, //=)
print("\nOperator Penugasan:")
c = 10
print("c =", c)
c += 5
print("c += 5 ->", c)
c -= 3
print("c -= 3 ->", c)
c *= 2
print("c *= 2 ->", c)
c /= 4
print("c /= 4 ->", c)
c %= 3
print("c %= 3 ->", c)
c **= 2
print("c **= 2 ->", c)
c //= 2
print("c //= 2 ->", c)

